"""Small, repeatable Training I/O runner for the AI SSD Training Cases.

The runner intentionally measures storage supply behavior instead of model
accuracy.  It uses only the Python standard library so it can run on a clean
Windows test host.  Use --prepare only for a small smoke dataset; qualification
runs should point --data-dir at the prepared workload dataset from the plan.
"""

